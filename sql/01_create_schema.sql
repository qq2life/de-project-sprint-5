-- PostgreSQL: создание новых сущностей без удаления данных существующего хранилища.
BEGIN;
CREATE SCHEMA IF NOT EXISTS stg;
CREATE SCHEMA IF NOT EXISTS dds;
CREATE SCHEMA IF NOT EXISTS cdm;

CREATE TABLE IF NOT EXISTS stg.api_couriers (
    courier_id TEXT PRIMARY KEY,
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS stg.api_deliveries (
    delivery_id TEXT PRIMARY KEY,
    order_id TEXT NOT NULL,
    courier_id TEXT NOT NULL,
    order_ts TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    delivery_ts TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_api_deliveries_delivery_ts ON stg.api_deliveries(delivery_ts);
CREATE INDEX IF NOT EXISTS ix_api_deliveries_order_id ON stg.api_deliveries(order_id);

CREATE TABLE IF NOT EXISTS dds.dm_couriers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id TEXT NOT NULL UNIQUE,
    courier_name TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS dds.fct_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id TEXT NOT NULL UNIQUE,
    order_id TEXT NOT NULL,
    courier_id BIGINT NOT NULL REFERENCES dds.dm_couriers(id),
    order_ts TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    delivery_ts TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    rate SMALLINT NOT NULL CHECK (rate BETWEEN 1 AND 5),
    tip_sum NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (tip_sum >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_fct_deliveries_order_id ON dds.fct_deliveries(order_id);
CREATE INDEX IF NOT EXISTS ix_fct_deliveries_courier_id ON dds.fct_deliveries(courier_id);

CREATE TABLE IF NOT EXISTS cdm.dm_courier_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id TEXT NOT NULL,
    courier_name TEXT NOT NULL,
    settlement_year INTEGER NOT NULL CHECK (settlement_year BETWEEN 2000 AND 2200),
    settlement_month INTEGER NOT NULL CHECK (settlement_month BETWEEN 1 AND 12),
    orders_count INTEGER NOT NULL CHECK (orders_count >= 0),
    orders_total_sum NUMERIC(18,2) NOT NULL CHECK (orders_total_sum >= 0),
    rate_avg NUMERIC(8,5) NOT NULL CHECK (rate_avg BETWEEN 1 AND 5),
    order_processing_fee NUMERIC(18,2) NOT NULL CHECK (order_processing_fee >= 0),
    courier_order_sum NUMERIC(18,2) NOT NULL CHECK (courier_order_sum >= 0),
    courier_tips_sum NUMERIC(18,2) NOT NULL CHECK (courier_tips_sum >= 0),
    courier_reward_sum NUMERIC(18,2) NOT NULL CHECK (courier_reward_sum >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_dm_courier_ledger UNIQUE (courier_id, settlement_year, settlement_month)
);
COMMIT;
